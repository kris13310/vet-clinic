-- =====================================================================
-- Veterinary Clinic: Supabase (PostgreSQL) schema
-- Run once: Supabase Dashboard > SQL Editor > New query > paste > Run.
-- Safe to run again (everything uses IF NOT EXISTS).
-- =====================================================================

CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR(120) NOT NULL,
  username      VARCHAR(50)  NOT NULL,
  email         VARCHAR(190) NOT NULL,
  phone         VARCHAR(40),
  address       VARCHAR(255),
  avatar_path   TEXT,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(20)  NOT NULL DEFAULT 'Veterinary Staff'
                CHECK (role IN ('Administrator','Veterinarian','Veterinary Staff','Pet Owner')),
  status        VARCHAR(10)  NOT NULL DEFAULT 'Active' CHECK (status IN ('Active','Inactive')),
  created_at    TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);
-- usernames and emails are case-insensitive (like the MySQL version)
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower    ON users (LOWER(email));

CREATE TABLE IF NOT EXISTS pets (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  species     VARCHAR(60)  NOT NULL DEFAULT 'Other',
  breed       VARCHAR(120),
  owner_name  VARCHAR(120) NOT NULL,
  owner_email VARCHAR(190),
  owner_phone VARCHAR(40),
  address     VARCHAR(255),
  age         VARCHAR(40),
  gender      VARCHAR(10) DEFAULT 'Unknown' CHECK (gender IN ('Male','Female','Unknown')),
  notes       TEXT,
  photo_path  TEXT,                       -- public URL of the picture in Supabase Storage
  created_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);
CREATE INDEX IF NOT EXISTS idx_pets_owner_email ON pets (LOWER(owner_email));

CREATE TABLE IF NOT EXISTS appointments (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id           BIGINT NOT NULL REFERENCES pets(id) ON DELETE CASCADE,
  veterinarian_id  BIGINT REFERENCES users(id) ON DELETE SET NULL,
  appointment_date DATE NOT NULL,
  appointment_time TIME NOT NULL,
  purpose          VARCHAR(255) NOT NULL,
  status           VARCHAR(12) NOT NULL DEFAULT 'Pending'
                   CHECK (status IN ('Pending','Confirmed','In Progress','Completed','Cancelled')),
  notes            TEXT,
  cancelled_by     VARCHAR(10),          -- 'Owner' or 'Clinic'
  created_at       TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);
CREATE INDEX IF NOT EXISTS idx_appt_slot ON appointments (appointment_date, appointment_time, status);
CREATE INDEX IF NOT EXISTS idx_appt_pet  ON appointments (pet_id);



-- Clinical reports are created by the assigned veterinarian and belong to one appointment and pet.
CREATE TABLE IF NOT EXISTS medical_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE CASCADE,
  pet_id BIGINT NOT NULL REFERENCES pets(id) ON DELETE CASCADE,
  veterinarian_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  diagnosis TEXT NOT NULL,
  symptoms TEXT NOT NULL,
  observations TEXT,
  treatment TEXT NOT NULL,
  medication TEXT,
  recommendations TEXT,
  follow_up_date DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_medical_reports_pet ON medical_reports (pet_id, created_at DESC);

CREATE TABLE IF NOT EXISTS vaccinations (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id          BIGINT NOT NULL REFERENCES pets(id) ON DELETE CASCADE,
  vaccine         VARCHAR(120) NOT NULL,
  date_given      DATE NOT NULL,
  next_due        DATE,
  veterinarian_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  notes           TEXT,
  created_at      TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);
CREATE INDEX IF NOT EXISTS idx_vax_pet ON vaccinations (pet_id);

CREATE TABLE IF NOT EXISTS adoption_records (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_name      VARCHAR(120) NOT NULL,
  species       VARCHAR(40)  NOT NULL,
  breed         VARCHAR(120),
  age           VARCHAR(40),
  gender        VARCHAR(20),
  health_status VARCHAR(80) DEFAULT 'Unknown',
  status        VARCHAR(10) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Pending','Adopted')),
  reason        TEXT,
  adopter_name  VARCHAR(120),
  adopted_at    DATE,
  photo_path    TEXT,
  created_at    TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);
ALTER TABLE adoption_records ADD COLUMN IF NOT EXISTS photo_path TEXT;

CREATE TABLE IF NOT EXISTS clinic_settings (
  id          SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  clinic_name VARCHAR(160) NOT NULL DEFAULT 'City Veterinary Office',
  email       VARCHAR(190),
  phone       VARCHAR(40),
  address     VARCHAR(255),
  updated_at  TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);

CREATE TABLE IF NOT EXISTS notifications (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  appointment_id BIGINT REFERENCES appointments(id) ON DELETE SET NULL,
  type           VARCHAR(30)  NOT NULL,
  title          VARCHAR(160) NOT NULL,
  message        VARCHAR(500) NOT NULL,
  is_read        SMALLINT NOT NULL DEFAULT 0,
  created_at     TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications (user_id, is_read, created_at);

-- Pet-owner adoption applications. One application per owner and listed pet.
CREATE TABLE IF NOT EXISTS adoption_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  adoption_id BIGINT NOT NULL REFERENCES adoption_records(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  applicant_name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  address VARCHAR(255) NOT NULL,
  message TEXT,
  status VARCHAR(12) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending','Approved','Rejected','Withdrawn')),
  staff_notes TEXT,
  reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (adoption_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_adoption_apps_status ON adoption_applications (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_adoption_apps_user ON adoption_applications (user_id, created_at DESC);

-- days / hours when the clinic or the doctor is NOT available (managed by the administrator)
CREATE TABLE IF NOT EXISTS clinic_closures (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  closure_date DATE NOT NULL,
  start_time   TIME,
  end_time     TIME,
  type         VARCHAR(30) NOT NULL DEFAULT 'Doctor Unavailable',
  reason       VARCHAR(190),
  created_by   BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at   TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_closure_date ON clinic_closures (closure_date);

-- login sessions (Vercel containers are temporary, so PHP sessions are kept here)
CREATE TABLE IF NOT EXISTS php_sessions (
  id         VARCHAR(128) PRIMARY KEY,
  data       TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- SECURITY: Supabase exposes the "public" schema through its own web API.
-- The app talks to the database directly from the server, so lock that API out:
-- Row Level Security ON with no policies = no access for the public (anon) key.
-- =====================================================================
ALTER TABLE users            ENABLE ROW LEVEL SECURITY;
ALTER TABLE pets             ENABLE ROW LEVEL SECURITY;
ALTER TABLE appointments     ENABLE ROW LEVEL SECURITY;
ALTER TABLE vaccinations     ENABLE ROW LEVEL SECURITY;
ALTER TABLE medical_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE adoption_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE clinic_settings  ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications    ENABLE ROW LEVEL SECURITY;
ALTER TABLE adoption_applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE clinic_closures  ENABLE ROW LEVEL SECURITY;
ALTER TABLE php_sessions     ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES    IN SCHEMA public FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;

