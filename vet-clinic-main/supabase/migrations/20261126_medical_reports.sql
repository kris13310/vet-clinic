-- Apply this once to an existing Supabase project to enable veterinarian medical reports.
CREATE TABLE IF NOT EXISTS public.medical_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id BIGINT NOT NULL UNIQUE REFERENCES public.appointments(id) ON DELETE CASCADE,
  pet_id BIGINT NOT NULL REFERENCES public.pets(id) ON DELETE CASCADE,
  veterinarian_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
  diagnosis TEXT NOT NULL,
  symptoms TEXT NOT NULL,
  observations TEXT,
  treatment TEXT NOT NULL,
  medication TEXT,
  recommendations TEXT,
  follow_up_date DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_medical_reports_pet ON public.medical_reports (pet_id, created_at DESC);
ALTER TABLE public.medical_reports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.medical_reports FROM anon, authenticated;
