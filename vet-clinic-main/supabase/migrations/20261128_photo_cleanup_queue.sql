-- Retryable cleanup queue for pet/profile photos that Supabase Storage could not delete.
-- Safe to run repeatedly.
CREATE TABLE IF NOT EXISTS photo_cleanup_queue (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  object_path TEXT NOT NULL UNIQUE,
  attempts INTEGER NOT NULL DEFAULT 0,
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS photo_cleanup_queue_created_at_idx ON photo_cleanup_queue (created_at);
ALTER TABLE photo_cleanup_queue ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE photo_cleanup_queue FROM anon, authenticated;
