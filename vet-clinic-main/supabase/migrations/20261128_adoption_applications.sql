-- Pet-owner adoption applications for the existing VETCARE Supabase database.
-- Safe to run more than once in Supabase SQL Editor.

CREATE TABLE IF NOT EXISTS public.adoption_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  adoption_id BIGINT NOT NULL REFERENCES public.adoption_records(id) ON DELETE RESTRICT,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
  applicant_name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  address VARCHAR(255) NOT NULL,
  message TEXT,
  status VARCHAR(12) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending','Approved','Rejected','Withdrawn')),
  staff_notes TEXT,
  reviewed_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_adoption_apps_one_pending
  ON public.adoption_applications (adoption_id, user_id)
  WHERE status='Pending';
CREATE INDEX IF NOT EXISTS idx_adoption_apps_status
  ON public.adoption_applications (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_adoption_apps_user
  ON public.adoption_applications (user_id, created_at DESC);

ALTER TABLE public.adoption_applications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.adoption_applications FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.adoption_applications_id_seq FROM anon, authenticated;
